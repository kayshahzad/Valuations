def convert_to_usd(value: float, currency: str, fiscal_year: int) -> float:
    """Convert a financial value to USD using annual average FX rate."""
    if currency == "USD" or currency is None:
        return value
    rates = ANNUAL_AVG_FX_TO_USD.get(currency.upper(), {})
    rate = rates.get(fiscal_year)
    if rate is None:
        # Fallback: use most recent known rate
        known_years = sorted(rates.keys())
        if known_years:
            rate = rates[known_years[-1]]
        else:
            # Unknown currency — log warning, return unconverted
            print(f"  ⚠ No FX rate for {currency} FY{fiscal_year} — storing unconverted")
            return value
    return value * rate
